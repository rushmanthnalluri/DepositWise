const form = document.querySelector('#prediction-form');
const submitButton = document.querySelector('#submit-button');
const apiStatus = document.querySelector('#api-status');
const statusDot = document.querySelector('.status-dot');
const emptyState = document.querySelector('#result-empty');
const resultContent = document.querySelector('#result-content');
const resultError = document.querySelector('#result-error');

async function checkHealth() {
  try {
    const response = await fetch('/health');
    const data = await response.json();
    if (!response.ok) throw new Error('Health endpoint unavailable');
    apiStatus.textContent = data.model_loaded ? 'Model ready' : 'API online · model not trained';
    statusDot.classList.toggle('online', Boolean(data.model_loaded));
  } catch (_) {
    apiStatus.textContent = 'API connection unavailable';
  }
}

form.addEventListener('submit', async (event) => {
  event.preventDefault();
  resultError.hidden = true;
  submitButton.disabled = true;
  submitButton.querySelector('span').textContent = 'Calculating estimate…';
  const values = Object.fromEntries(new FormData(form).entries());
  for (const key of ['age', 'balance', 'day', 'campaign', 'pdays', 'previous']) values[key] = Number(values[key]);
  try {
    const response = await fetch('/predict', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ customer: values })
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.detail || 'Prediction request failed.');
    const probability = Math.max(0, Math.min(1, Number(data.subscription_probability)));
    const percentage = (probability * 100).toFixed(1);
    emptyState.hidden = true;
    resultContent.hidden = false;
    document.querySelector('#probability-value').textContent = percentage;
    document.querySelector('#meter-fill').style.width = `${percentage}%`;
    document.querySelector('#outcome').textContent = data.predicted_subscription ? 'Above baseline threshold' : 'Below baseline threshold';
    document.querySelector('#outcome').classList.toggle('negative', !data.predicted_subscription);
    document.querySelector('#threshold-value').textContent = `${(Number(data.threshold) * 100).toFixed(0)}%`;
    document.querySelector('#model-status').textContent = 'Prediction returned';
    document.querySelector('#result-note').textContent = data.note || 'Estimate generated by the current model.';
    apiStatus.textContent = 'Model ready';
    statusDot.classList.add('online');
  } catch (error) {
    resultError.textContent = error.message;
    resultError.hidden = false;
    if (error.message.toLowerCase().includes('model artifact is missing')) {
      apiStatus.textContent = 'API online · model not trained';
      statusDot.classList.remove('online');
    }
  } finally {
    submitButton.disabled = false;
    submitButton.querySelector('span').textContent = 'Estimate subscription likelihood';
  }
});

form.addEventListener('reset', () => {
  resultError.hidden = true;
  resultContent.hidden = true;
  emptyState.hidden = false;
});

checkHealth();
